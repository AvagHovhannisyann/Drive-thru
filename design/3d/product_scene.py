def mat(name, color, rough=0.5, metal=0.0, trans=0.0, ior=1.45, alpha=1.0, coat=0.0, img=None, img_alpha=False, emis=0.0, sss=0.0):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    b = nt.nodes["Principled BSDF"]
    b.inputs["Base Color"].default_value = (*color, 1)
    b.inputs["Roughness"].default_value = rough
    b.inputs["Metallic"].default_value = metal
    b.inputs["Transmission Weight"].default_value = trans
    b.inputs["IOR"].default_value = ior
    b.inputs["Alpha"].default_value = alpha
    b.inputs["Coat Weight"].default_value = coat
    b.inputs["Subsurface Weight"].default_value = sss
    if img and os.path.exists(img):
        it = nt.nodes.new("ShaderNodeTexImage")
        it.image = bpy.data.images.load(img, check_existing=True)
        uv = nt.nodes.new("ShaderNodeUVMap")
        nt.links.new(uv.outputs[0], it.inputs[0])
        if img_alpha:
            # print over base material: mix by alpha
            mix = nt.nodes.new("ShaderNodeMix"); mix.data_type = "RGBA"
            nt.links.new(it.outputs["Alpha"], mix.inputs[0])
            mix.inputs[6].default_value = (*color, 1)
            nt.links.new(it.outputs["Color"], mix.inputs[7])
            nt.links.new(mix.outputs[2], b.inputs["Base Color"])
            # printed areas are opaque, rest keeps transmission
            inv = nt.nodes.new("ShaderNodeMath"); inv.operation = "SUBTRACT"; inv.inputs[0].default_value = trans
            mul = nt.nodes.new("ShaderNodeMath"); mul.operation = "MULTIPLY"; mul.inputs[1].default_value = trans
            nt.links.new(it.outputs["Alpha"], mul.inputs[0]); nt.links.new(mul.outputs[0], inv.inputs[1])
            nt.links.new(inv.outputs[0], b.inputs["Transmission Weight"])
        else:
            nt.links.new(it.outputs["Color"], b.inputs["Base Color"])
    return m


def lathe(name, profile, segs=96, mats=None, uv_wrap=True, cap_bottom=True):
    """Revolve (r, z) profile around Z. UV: u = angle/2pi, v = z normalised over printable band."""
    bm = bmesh.new()
    rings = []
    for k in range(segs):
        a = 2 * math.pi * k / segs
        ring = [bm.verts.new((r * math.cos(a), r * math.sin(a), z)) for (r, z) in profile]
        rings.append(ring)
    uvl = bm.loops.layers.uv.new("UVMap")
    zmin = min(p[1] for p in profile); zmax = max(p[1] for p in profile)
    for k in range(segs):
        r0, r1 = rings[k], rings[(k + 1) % segs]
        for i in range(len(profile) - 1):
            f = bm.faces.new((r0[i], r1[i], r1[i + 1], r0[i + 1]))
            u0, u1 = k / segs, (k + 1) / segs
            v0 = (profile[i][1] - zmin) / (zmax - zmin + 1e-9); v1 = (profile[i + 1][1] - zmin) / (zmax - zmin + 1e-9)
            for loop, (u, v) in zip(f.loops, ((u0, v0), (u1, v0), (u1, v1), (u0, v1))):
                loop[uvl].uv = (u, v)
    if cap_bottom:
        bm.faces.new([rings[k][0] for k in range(segs)][::-1])
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    for p in me.polygons:
        p.use_smooth = True
    ob = bpy.data.objects.new(name, me)
    sc.collection.objects.link(ob)
    for m in (mats or []):
        me.materials.append(m)
    return ob


def place(ob, x, y, z=0.0, rz=0.0, s=1.0):
    ob.location = (x, y, z)
    ob.rotation_euler = (0, 0, math.radians(rz))
    ob.scale = (s, s, s)


def hot_cup(name, x, y, h=0.135, rt=0.045, rb=0.031, rz=0.0, sleeve=True, lid_col=(0.92, 0.9, 0.86)):
    group = bpy.data.objects.new(name, None); sc.collection.objects.link(group)
    prof = [(rb, 0.0), (rb + 0.0005, 0.003)] + [(rb + (rt - rb) * t, h * t) for t in [i / 20 for i in range(1, 21)]]
    body = lathe(name + "_body", prof, mats=[mat(name + "_print", CREAM, rough=0.55, img=f"{B}/cup_wrap.png")])
    body.parent = group
    # rolled rim
    bpy.ops.mesh.primitive_torus_add(major_radius=rt + 0.001, minor_radius=0.0022, major_segments=96, minor_segments=12, location=(0, 0, h))
    rim = bpy.context.active_object; rim.data.materials.append(mat(name + "_rim", CREAM, rough=0.5)); rim.parent = group
    # lid (sip lid: domed with recessed ring)
    lp = [(0.0, h + 0.014), (rt * 0.55, h + 0.0145), (rt * 0.62, h + 0.012), (rt * 0.7, h + 0.016), (rt * 0.92, h + 0.017),
          (rt + 0.003, h + 0.010), (rt + 0.004, h + 0.002), (rt + 0.002, h - 0.003)]
    lid = lathe(name + "_lid", lp, mats=[mat(name + "_lidm", lid_col, rough=0.35, coat=0.2)], cap_bottom=False)
    lid.parent = group
    for p in lid.data.polygons:
        p.use_smooth = True
    if sleeve:
        zs0, zs1 = h * 0.28, h * 0.66
        sp = [(rb + (rt - rb) * (z / h) + 0.0018, z) for z in [zs0 + (zs1 - zs0) * i / 8 for i in range(9)]]
        sl = lathe(name + "_sleeve", sp, mats=[mat(name + "_sleevem", (0.55, 0.38, 0.24), rough=0.85, img=f"{B}/sleeve.png")], cap_bottom=False)
        sl.parent = group
    place(group, x, y, 0, rz)
    return group


def iced_cup(name, x, y, h=0.155, rt=0.049, rb=0.033, rz=0.0):
    group = bpy.data.objects.new(name, None); sc.collection.objects.link(group)
    prof = [(rb, 0.0)] + [(rb + (rt - rb) * t, h * t) for t in [i / 20 for i in range(1, 21)]]
    cup = lathe(name + "_pet", prof, mats=[mat(name + "_petm", (0.97, 0.98, 0.98), rough=0.03, trans=1.0, ior=1.45, img=f"{B}/iced_wrap.png", img_alpha=True)])
    cup.parent = group
    sol = bpy.data.objects.new(name + "_s", None)
    # drink: espresso layer over milk (two lathe solids slightly inside)
    def liquid(z0, z1, col, nm, rough=0.15, sss=0.0):
        pr = [(0.0, z0)] + [((rb + (rt - rb) * (z / h)) - 0.0012, z) for z in (z0, (z0 + z1) / 2, z1)] + [(0.0, z1)]
        o = lathe(name + nm, pr, mats=[mat(name + nm + "m", col, rough=rough, sss=sss)], cap_bottom=False)
        o.parent = group
    liquid(0.002, h * 0.55, (0.86, 0.78, 0.66), "_milk", sss=0.3)
    liquid(h * 0.55, h * 0.62, (0.42, 0.25, 0.13), "_mix")
    liquid(h * 0.62, h * 0.82, (0.16, 0.08, 0.04), "_espr")
    # ice cubes
    for i, (ix, iy, iz) in enumerate([(0.012, 0.004, 0.11), (-0.01, -0.012, 0.118), (-0.006, 0.014, 0.106), (0.014, -0.013, 0.122)]):
        bpy.ops.mesh.primitive_cube_add(size=0.018, location=(ix, iy, iz), rotation=(0.3 * i, 0.5, 0.2 * i))
        ice = bpy.context.active_object
        m = ice.modifiers.new("b", "BEVEL"); m.width = 0.003; m.segments = 3
        ice.data.materials.append(mat(name + f"_ice{i}", (0.95, 0.98, 1.0), rough=0.05, trans=1.0, ior=1.31))
        ice.parent = group
    # flat lid + straw
    lp = [(0.0, h + 0.004), (rt + 0.002, h + 0.004), (rt + 0.003, h - 0.004)]
    lid = lathe(name + "_lid", lp, mats=[mat(name + "_lidm", (0.97, 0.98, 0.98), rough=0.05, trans=1.0)], cap_bottom=False)
    lid.parent = group
    bpy.ops.mesh.primitive_cylinder_add(radius=0.004, depth=0.22, location=(0.008, 0.0, h + 0.02), rotation=(0.0, math.radians(8), 0))
    st = bpy.context.active_object; st.data.materials.append(mat(name + "_straw", PRIMARY, rough=0.4)); st.parent = group
    place(group, x, y, 0, rz)
    return group


def uv_box(name, x0, y0, z0, x1, y1, z1, m_side, m_front=None, m_top=None, front_axis="-y"):
    bpy.ops.mesh.primitive_cube_add(size=1)
    ob = bpy.context.active_object
    ob.name = name
    ob.scale = ((x1 - x0), (y1 - y0), (z1 - z0))
    ob.location = ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    me = ob.data
    me.materials.append(m_side)
    me.materials.append(m_front or m_side)
    me.materials.append(m_top or m_side)
    uvl = me.uv_layers.active
    x0, x1, y0, y1, z0, z1 = -(x1 - x0) / 2, (x1 - x0) / 2, -(y1 - y0) / 2, (y1 - y0) / 2, -(z1 - z0) / 2, (z1 - z0) / 2
    ob_loc = Vector((0, 0, 0))
    for p in me.polygons:
        n = p.normal
        if (front_axis == "-y" and n.y < -0.9):
            p.material_index = 1
        elif n.z > 0.9:
            p.material_index = 2
        # simple planar uv per face
        for li in p.loop_indices:
            v = me.vertices[me.loops[li].vertex_index].co
            if abs(n.y) > 0.9:
                uvl.data[li].uv = ((v.x - x0) / (x1 - x0), (v.z - z0) / (z1 - z0))
            elif abs(n.x) > 0.9:
                uvl.data[li].uv = ((v.y - y0) / (y1 - y0), (v.z - z0) / (z1 - z0))
            else:
                uvl.data[li].uv = ((v.x - x0) / (x1 - x0), (v.y - y0) / (y1 - y0))
    m = ob.modifiers.new("b", "BEVEL"); m.width = 0.0015; m.segments = 2
    return ob


